import { expect, test } from '@playwright/test';
import { seedProfile } from '../../src/demo/fixtures';
import type { PrivateTask } from '../../src/api';

test('creating from a filtered scanner list preserves its URL context and submits one reviewed task', async ({ page }, testInfo) => {
  const profile = seedProfile();
  const tasks: PrivateTask[] = Array.from({ length: 40 }, (_, index) => ({ id: `task-${index}`, status: 'running', host_list: [`host-${index}.example.test`], port_list: [443], created_at: 1800000000 + index, result_count: 0 }));
  const frames: Array<{ type: string; data: Record<string, unknown> }> = [];
  await page.route('**/runtime-config.js', route => route.fulfill({ contentType: 'application/javascript', body: 'window.__APCOSYS_CONFIG__={dataMode:"live",apiBaseUrl:"/backend"};' }));
  await page.route('**/backend/**', route => route.fulfill({ json: profile }));
  await page.routeWebSocket('**/backend/ws', socket => socket.onMessage(raw => {
    const frame = JSON.parse(String(raw)); frames.push(frame);
    const reply = (data: unknown) => socket.send(JSON.stringify({ id: frame.id, type: frame.type, data }));
    if (frame.type === 'private_tasks_get') reply(tasks);
    else if (frame.type === 'private_planning_tasks_get') reply([{ id: 'planned-1', host_list: ['host-scheduled.example.test'], port_list: [443], schedule: '0 0 3 * * *', user_name: 'alex_research' }]);
    else if (frame.type === 'private_task_add') {
      tasks.unshift({ id: 'new-task', status: 'queued', ...frame.data });
      reply({ task_id: 'new-task' });
    } else reply({ unread_count: 0 });
  }));
  const initial = '/scanner?tab=active&q=host&rows=10&page=2';
  await page.goto(initial);
  await expect(page.locator('.scanner-task-table tbody tr')).toHaveCount(10);
  await expect(page.getByRole('tab', { name: /^Active/ })).toHaveAttribute('aria-selected', 'true');
  await page.locator('.scanner-page').screenshot({ path: testInfo.outputPath('scanner-tasks-1440.png') });
  const firstTask = page.locator('.scanner-task-table tbody tr').first();
  await firstTask.getByRole('checkbox').check();
  await expect(page.getByRole('dialog', { name: 'Task details', exact: true })).toHaveCount(0);
  await firstTask.getByRole('checkbox').uncheck();
  await firstTask.locator('[data-label="Created"]').click();
  const details = page.getByRole('dialog', { name: 'Task details', exact: true });
  await expect(details.getByText('running', { exact: true })).toHaveCount(1);
  await expect(details.getByRole('progressbar')).toHaveCount(0);
  await details.getByText('Raw task data', { exact: true }).click();
  await expect(details.getByLabel('Task record source', { exact: true })).toContainText('host-10.example.test');
  await expect(details.getByRole('button', { name: 'Copy Task record', exact: true })).toBeVisible();
  await details.getByText('Raw task data', { exact: true }).click();
  await details.screenshot({ path: testInfo.outputPath('scanner-details-1440.png') });
  await page.setViewportSize({ width: 320, height: 844 });
  await details.screenshot({ path: testInfo.outputPath('scanner-details-320.png') });
  await details.getByRole('button', { name: 'Close', exact: true }).click();
  await expect(firstTask.locator('.scanner-target-button')).toBeFocused();
  await page.evaluate(() => window.scrollTo({ top: 0, left: 0, behavior: 'instant' }));
  await expect(page.locator('.scanner-task-table tbody tr').first().locator('.scanner-target-button')).toBeInViewport({ ratio: 1 });
  await page.screenshot({ path: testInfo.outputPath('scanner-initial-viewport-320.png'), fullPage: false });
  await page.locator('.scanner-page').screenshot({ path: testInfo.outputPath('scanner-tasks-320.png') });
  await page.getByRole('button', { name: 'Next', exact: true }).click();
  await expect(firstTask).toContainText('host-20.example.test');
  await expect.poll(async () => {
    const menu = await page.getByRole('button', { name: 'Open navigation', exact: true }).boundingBox();
    const table = await page.locator('.scanner-tasks-table-wrap').boundingBox();
    return menu && table ? table.y - menu.y - menu.height : -1;
  }).toBeGreaterThanOrEqual(12);
  await page.screenshot({ path: testInfo.outputPath('scanner-pagination-offset-320.png'), fullPage: false });
  await page.getByRole('button', { name: 'Previous', exact: true }).click();
  await expect(firstTask).toContainText('host-10.example.test');
  await page.setViewportSize({ width: 1440, height: 960 });
  await page.getByRole('tab', { name: /^Scheduled/ }).click();
  await expect(page.locator('.scanner-task-table--planned')).toContainText('host-scheduled.example.test');
  await expect(page.locator('.scanner-task-table--planned')).toContainText('Daily at 03:00 (scanner time)');
  await expect(page.locator('.scanner-task-table--planned code')).toHaveText('0 0 3 * * *');
  await page.locator('.scanner-page').screenshot({ path: testInfo.outputPath('scanner-scheduled-1440.png') });
  await page.setViewportSize({ width: 320, height: 844 });
  await page.locator('.scanner-page').screenshot({ path: testInfo.outputPath('scanner-scheduled-320.png') });
  await page.setViewportSize({ width: 1440, height: 960 });
  await page.goBack();
  await expect(page).toHaveURL(initial);
  await expect(page.locator('.scanner-task-table tbody tr').first()).toContainText('task-10');
  await page.getByRole('link', { name: 'New task', exact: true }).click();
  await expect(page.getByRole('link', { name: 'Back to tasks', exact: true })).toHaveAttribute('href', initial);
  await page.getByLabel('Hosts and IP addresses', { exact: true }).fill('host-new.example.test');
  await page.getByLabel('Port list', { exact: true }).fill('443');
  expect(frames.filter(frame => frame.type === 'private_task_add')).toEqual([]);
  await page.locator('.scanner-page').screenshot({ path: testInfo.outputPath('scanner-new-task-1440.png') });
  await page.setViewportSize({ width: 320, height: 844 });
  await page.locator('.scanner-page').screenshot({ path: testInfo.outputPath('scanner-new-task-320.png') });
  await page.setViewportSize({ width: 1440, height: 960 });
  await page.getByRole('button', { name: 'Review task', exact: true }).click();
  const review = page.getByRole('dialog', { name: 'Review scan task', exact: true });
  await expect(review).toContainText('host-new.example.test');
  await expect(review.locator('.scanner-estimated-total dd')).toHaveText('1');
  expect(frames.filter(frame => frame.type === 'private_task_add')).toEqual([]);
  await review.getByRole('button', { name: 'Create scan task', exact: true }).click();
  await expect(page).toHaveURL(url => url.pathname === '/scanner' && url.searchParams.get('tab') === 'active' && url.searchParams.get('q') === 'host' && url.searchParams.get('rows') === '10' && url.searchParams.get('page') === '2' && url.searchParams.get('created') === 'new-task');
  expect(frames.filter(frame => frame.type === 'private_task_add')).toHaveLength(1);
  expect(frames.find(frame => frame.type === 'private_task_add')?.data).toMatchObject({ host_list: ['host-new.example.test'], port_list: [443] });
  await expect(page.locator('.scanner-page > .alert--success')).toHaveCount(0);
});
